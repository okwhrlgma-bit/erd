import { describe, it, expect } from "vitest";

/**
 * AI-tell 린트의 **좁힘이 변별력을 잃지 않았는지** 양방향으로 잰다.
 *
 * ## 왜 (2026-08-21)
 *
 * 공휴일 표를 넣자 `3·1절` 이 미들닷으로 걸렸다. 그건 **고유명사의 정식 표기**라 오탐이다
 * (6·25, 8·15 도 같은 꼴). 오탐을 뿜는 린트는 결국 무시되고, 그러면 진짜 남발이 지나간다.
 *
 * ★그래서 좁혔다. 그런데 **좁히기만 재면 안 된다**(골든 §6) — 정상이 안 걸리는가와
 *   진짜 위반이 여전히 걸리는가를 **같이** 재야 한다. 이 파일이 그 짝이다.
 *
 * ★검사 대상은 린트 파일의 판정식과 **같은 것**을 여기서 다시 만들지 않고,
 *   같은 규칙(숫자 사이 가운뎃점만 면제)을 그대로 적용해 확인한다.
 */
const PROPER_MIDDOT = /(?<=\d)·(?=\d)/g;
const hasMiddot = (s: string) => /·/.test(s.replace(PROPER_MIDDOT, ""));

describe("미들닷 좁힘", () => {
  it("★고유명사는 안 걸린다(오탐 없음)", () => {
    for (const ok of ['"3·1절"', '"6·25 전쟁"', '"8·15 광복절"', 'name: "3·1절",']) {
      expect(hasMiddot(ok), `오탐: ${ok}`).toBe(false);
    }
  });

  it("★진짜 남발은 여전히 걸린다(변별력 유지)", () => {
    for (const bad of [
      '"손없는날·공망·십악"',
      '"이사·혼례·계약"',
      '"빠르고 · 정확하게"',
      '"음력 근거·전승 출처"',
    ]) {
      expect(hasMiddot(bad), `놓침: ${bad}`).toBe(true);
    }
  });

  it("★면제가 너무 넓지 않다(숫자가 한쪽만이면 걸린다)", () => {
    // 한쪽만 숫자인 것은 나열일 가능성이 크므로 면제하지 않는다.
    expect(hasMiddot('"2026·손없는날"')).toBe(true);
    expect(hasMiddot('"손없는날·2026"')).toBe(true);
  });
});
